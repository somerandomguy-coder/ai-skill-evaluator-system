const SIMPLE_CLAIMS = [
  "// >>> claims",
  "export function checkClaim(text, comments) {",
  "  const supportIds = supporters(text, comments);",
  "  return { text, supportIds, supported: supportIds.length >= 1, sweeping: false, singlesOut: false };",
  "}",
  "// <<< claims",
].join("\n");

function swapClaims(source: string, replacement: string): string {
  const start = source.indexOf("// >>> claims");
  const endMarker = "// <<< claims";
  const end = source.indexOf(endMarker);
  if (start < 0 || end < 0) throw new Error("seed-solutions: claim markers missing");
  return source.slice(0, start) + replacement + source.slice(end + endMarker.length);
}

